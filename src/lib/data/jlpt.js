// 다음 시험일 — 매년 7월·12월 첫째 일요일
export function nextExam(from = new Date()) {
  const base = new Date(from.getFullYear(), from.getMonth(), from.getDate())
  const firstSunday = (y, m) => {
    const d = new Date(y, m, 1)
    d.setDate(1 + ((7 - d.getDay()) % 7))
    return d
  }
  for (let y = base.getFullYear(); ; y++) {
    for (const m of [6, 11]) {
      const d = firstSunday(y, m)
      if (d >= base) return { date: d, dday: Math.round((d - base) / 86400000) }
    }
  }
}

